def load_minute_series() -> tuple[pd.DataFrame, pd.DataFrame, pd.DatetimeIndex]:
    df = pd.read_csv(SCREENED_CSV)
    df["ts"] = pd.to_datetime(df["timestamp"], utc=True)

    full_idx = pd.date_range(T_START_STR, T_END_STR, freq="1min")

    # Flow and speed tables indexed by (ts) with MultiIndex columns (site_id, lane)
    piv_q = df.pivot_table(index="ts", columns=["site_id", "lane"], values="flow_veh_h", aggfunc="mean")
    piv_v = df.pivot_table(index="ts", columns=["site_id", "lane"], values="speed_kmh", aggfunc="mean")

    # Keep only valid columns, reindex to full 1-min grid, and interpolate tiny 1-2 min gaps
    piv_q = piv_q.reindex(full_idx).interpolate(method="linear", limit_direction="both")
    piv_v = piv_v.reindex(full_idx).interpolate(method="linear", limit_direction="both")

    # NDW speeds can be -1/0 when zero flow; replace non-positive speeds with column median positive speed
    for col in piv_v.columns:
        pos = piv_v[col] > 0
        if pos.any():
            med = float(piv_v.loc[pos, col].median())
            piv_v[col] = piv_v[col].where(pos, med)
        else:
            piv_v[col] = 85.0

    # Quantize flows cleanly to integer veh/min * 60 (multiple of 60)
    piv_q = (piv_q / 60.0).round().clip(lower=0.0) * 60.0
    return piv_q, piv_v, full_idx


def site_totals(piv_q: pd.DataFrame, piv_v: pd.DataFrame, site: str, lanes: list[str] | None = None) -> tuple[pd.Series, pd.Series]:
    cols = [(site, l) for l in lanes] if lanes else [c for c in piv_q.columns if c[0] == site]
    q_sum = piv_q[cols].sum(axis=1)
    q_vals = piv_q[cols]
    v_vals = piv_v[cols]
    # Flow-weighted space-mean proxy across the selected lanes; fallback to simple mean if flow == 0
    num = (q_vals * v_vals).sum(axis=1)
    v_mean = pd.Series(
        np.where(q_sum > 0, num / q_sum.replace(0, np.nan), v_vals.mean(axis=1)),
        index=piv_q.index,
    )
    return q_sum, v_mean


def build() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "patches").mkdir(parents=True, exist_ok=True)

    piv_q, piv_v, full_idx = load_minute_series()
    node_coords = {n["id"]: n["coord"] for n in NODES}

    # Estimate free-flow speed (75th percentile of minute speeds or >60 km/h mean) per link
    def free_flow_mps(site: str, lanes: list[str] | None = None, default_kmh: float = 95.0) -> float:
        _, v_ser = site_totals(piv_q, piv_v, site, lanes)
        uncongested = v_ser[v_ser >= 60.0]
        kmh = float(uncongested.mean()) if len(uncongested) > 0 else default_kmh
        return round(kmh / 3.6, 3)

    # Link definitions: pipe 0 = rightmost lane group
    # On L2 (0778ra_1): pipe 0 = lane5 (outer exit -> L4), pipe 1 = lane4 (inner exit -> L3),
    # pipes 2..4 = lane3..lane1 (mainline -> L5).
    link_specs = [
        {"id": 0, "u": 0, "v": 1, "site": "RWS01_MONIBAS_0151hrr0764ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "label": "0764ra (A15 W)", "c_per_lane": 0.60},
        {"id": 1, "u": 1, "v": 2, "site": "RWS01_MONIBAS_0151hrr0770ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "label": "0770ra", "c_per_lane": 0.60},
        {"id": 2, "u": 2, "v": 3, "site": "RWS01_MONIBAS_0151hrr0778ra_1", "lanes": 5, "pipes": [{"lanes": 1}] * 5, "friction": 0.95, "moves": {"4": [0], "3": [1], "5": [2, 3, 4]}, "label": "0778ra_1 (5L approach)", "c_per_lane": 0.60},
        {"id": 3, "u": 3, "v": 4, "site": "RWS01_MONIBAS_0150vwa0780ra", "lane_filter": ["lane1"], "lanes": 1, "pipes": [{"lanes": 1}], "label": "vwa0780ra L1 (N3 queue)", "c_per_lane": 0.55},
        {"id": 4, "u": 3, "v": 5, "site": "RWS01_MONIBAS_0150vwa0780ra", "lane_filter": ["lane2"], "lanes": 1, "pipes": [{"lanes": 1}], "label": "vwa0780ra L2 (N3 free)", "c_per_lane": 0.55},
        {"id": 5, "u": 3, "v": 6, "site": "RWS01_MONIBAS_0151hrr0782ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "label": "0782ra", "c_per_lane": 0.60},
        {"id": 6, "u": 6, "v": 7, "site": "RWS01_MONIBAS_0151hrr0784ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "label": "0784ra", "c_per_lane": 0.60},
        {"id": 7, "u": 8, "v": 7, "site": "GEO0K_K_RWSTI358186", "lanes": 1, "pipes": [{"lanes": 1}], "label": "vwb078800 (on-ramp)", "c_per_lane": 0.50},
        {"id": 8, "u": 7, "v": 9, "site": "RWS01_MONIBAS_0151hrr0790ra", "lanes": 4, "pipes": [{"lanes": 1}] * 4, "label": "0790ra (4L merge)", "c_per_lane": 0.60},
        {"id": 9, "u": 9, "v": 10, "site": "RWS01_MONIBAS_0151hrr0794ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "label": "0794ra", "c_per_lane": 0.60},
        {"id": 10, "u": 10, "v": 11, "site": "RWS01_MONIBAS_0151hrr0797ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "moves": {"11": [0], "12": [0, 1, 2]}, "label": "0797ra", "c_per_lane": 0.60},
        {"id": 11, "u": 11, "v": 12, "site": "GEO0C_Z_RWSTI358373", "lanes": 1, "pipes": [{"lanes": 1}], "label": "vwa080517 (Sliedrecht off)", "c_per_lane": 0.55},
        {"id": 12, "u": 11, "v": 13, "site": "RWS01_MONIBAS_0151hrr0806ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "label": "0806ra", "c_per_lane": 0.60},
        {"id": 13, "u": 13, "v": 14, "site": "RWS01_MONIBAS_0151hrr0808ra", "lanes": 3, "pipes": [{"lanes": 1}] * 3, "label": "0808ra (A15 E)", "c_per_lane": 0.60},
        {"id": 14, "u": 4, "v": 15, "site": "RWS01_MONIBAS_0150vwa0780ra", "lane_filter": ["lane1"], "lanes": 1, "pipes": [{"lanes": 1}], "label": "N3 stop-bar gate (L1)", "c_per_lane": 0.55, "skip_obs": True},
        {"id": 15, "u": 12, "v": 16, "site": "GEO0C_Z_RWSTI358373", "lanes": 1, "pipes": [{"lanes": 1}], "label": "Sliedrecht gate", "c_per_lane": 0.55, "skip_obs": True},
    ]

    features: list[dict] = []
    for n in NODES:
        features.append({
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": list(n["coord"])},
            "properties": {"id": n["id"], "type": n["type"], "signals": []},
        })

    for spec in link_specs:
        c0 = node_coords[spec["u"]]
        c1 = node_coords[spec["v"]]
        length = round(haversine_m(c0, c1), 1)
        u_mps = free_flow_mps(spec["site"], spec.get("lane_filter"))
        lanes = spec["lanes"]
        c_total = round(spec["c_per_lane"] * lanes, 4)
        props: dict = {
            "id": spec["id"],
            "node_up": spec["u"],
            "node_down": spec["v"],
            "length": length,
            "speed": u_mps,
            "lanes": lanes,
            "capacity": c_total,
            "fd_u": u_mps,
            "fd_w": 5.0,
            "fd_kx": 0.14,
            "fd_c": spec["c_per_lane"],
            "label": spec["label"],
            "ndw_site": spec["site"],
        }
        if "pipes" in spec:
            props["pipes"] = spec["pipes"]
        if "friction" in spec:
            props["friction"] = spec["friction"]
        if "moves" in spec:
            props["moves"] = spec["moves"]
        features.append({
            "type": "Feature",
            "geometry": {"type": "LineString", "coordinates": [list(c0), list(c1)]},
            "properties": props,
        })

    geojson = {"type": "FeatureCollection", "features": features}
    (OUT_DIR / "network.geojson").write_text(json.dumps(geojson, indent=2), encoding="utf-8")

    # Config
    config = {
        "start_time": START_SEC,
        "duration": SIM_DURATION,
        "classes": ["car"],
        "merge": "capacity",
    }
    (OUT_DIR / "config.json").write_text(json.dumps(config, indent=2), encoding="utf-8")

    # Demand at 1-minute resolution
    # Entry 0 (0764ra) splits across:
    #   Dest 4 (vwa0780ra L1): arrival flow measured at 0778ra_1 lane4
    #   Dest 5 (vwa0780ra L2): measured at vwa0780ra lane2
    #   Dest 12 (vwa080517):   measured at GEO0C_Z_RWSTI358373 lane1
    #   Dest 14 (0808ra):      residual q(0764ra) - q_780_L1 - q_780_L2 - q_805
    # Entry 8 (vwb078800) -> Dest 14 (0808ra)
    q_0764, _ = site_totals(piv_q, piv_v, "RWS01_MONIBAS_0151hrr0764ra")
    q_778_l4 = piv_q[("RWS01_MONIBAS_0151hrr0778ra_1", "lane4")]
    q_780_l1 = piv_q[("RWS01_MONIBAS_0150vwa0780ra", "lane1")]
    v_780_l1 = piv_v[("RWS01_MONIBAS_0150vwa0780ra", "lane1")]
    q_780_l2 = piv_q[("RWS01_MONIBAS_0150vwa0780ra", "lane2")]
    q_805 = piv_q[("GEO0C_Z_RWSTI358373", "lane1")]
    v_805 = piv_v[("GEO0C_Z_RWSTI358373", "lane1")]
    q_788 = piv_q[("GEO0K_K_RWSTI358186", "lane1")]

    demand_rows: list[dict] = []
    gate_ops: list[dict] = []

    for idx_i, ts in enumerate(full_idx):
        t0 = START_SEC + idx_i * 60.0
        t1 = t0 + 60.0

        f_in = float(q_0764.loc[ts])
        f_off_l1 = float(q_778_l4.loc[ts])
        f_off_l2 = float(q_780_l2.loc[ts])
        f_off_805 = min(float(q_805.loc[ts]), max(0.0, f_in - f_off_l1 - f_off_l2))
        f_thru = max(0.0, f_in - f_off_l1 - f_off_l2 - f_off_805)
        f_on = float(q_788.loc[ts])

        od_flows = [
            (0, 15, f_off_l1),
            (0, 5, f_off_l2),
            (0, 16, f_off_805),
            (0, 14, f_thru),
            (8, 14, f_on),
        ]
        for o, d, flow_h in od_flows:
            cnt = int(round(flow_h / 60.0))
            if cnt <= 0:
                continue
            demand_rows.append({
                "period_start": t0,
                "period_end": t1,
                "origin": o,
                "destination": d,
                "flow": float(cnt * 60),
                "count": cnt,
            })

        # Gate op on Link 14 (N3 stop-bar downstream of vwa0780ra L1) when ramp speed < 60 km/h
        spd_780 = float(v_780_l1.loc[ts])
        qout_780 = float(q_780_l1.loc[ts])
        if spd_780 < 60.0:
            cap_s = round(max(0.05, qout_780 / 3600.0), 4)
        else:
            cap_s = 0.55
        gate_ops.append({
            "op": "set_link",
            "link": 14,
            "from": t0,
            "until": t1,
            "set": {"fd_c": cap_s, "capacity": cap_s},
        })

        # Gate op on Link 15 (Sliedrecht stop-bar downstream of vwa080517) when speed < 60 km/h
        spd_805 = float(v_805.loc[ts])
        qout_805 = float(q_805.loc[ts])
        if spd_805 < 60.0:
            cap_805 = round(max(0.05, qout_805 / 3600.0), 4)
        else:
            cap_805 = 0.55
        gate_ops.append({
            "op": "set_link",
            "link": 15,
            "from": t0,
            "until": t1,
            "set": {"fd_c": cap_805, "capacity": cap_805},
        })

    (OUT_DIR / "demand.json").write_text(json.dumps(demand_rows, indent=1), encoding="utf-8")

    # Coalesce adjacent identical gate values to keep gate.json crisp
    coalesced: list[dict] = []
    for op in gate_ops:
        if (
            coalesced
            and coalesced[-1]["link"] == op["link"]
            and coalesced[-1]["set"] == op["set"]
            and coalesced[-1]["until"] == op["from"]
        ):
            coalesced[-1]["until"] = op["until"]
        else:
            coalesced.append(op)

    # Only include throttled or transition windows (keep non-default + explicit restore)
    active_ops = []
    last_cap: dict[int, float] = {14: 0.55, 15: 0.55}
    for op in coalesced:
        lid = op["link"]
        c = op["set"]["fd_c"]
        if c < 0.5499 or last_cap[lid] < 0.5499:
            active_ops.append(op)
        last_cap[lid] = c

    gate = {
        "name": "gate",
        "description": "Downstream off-ramp metering from NDW 1-min detector speeds < 60 km/h on vwa0780ra L1 stop-bar (Link 14) and vwa080517 stop-bar (Link 15).",
        "ops": active_ops,
    }
    (OUT_DIR / "patches" / "gate.json").write_text(json.dumps(gate, indent=2), encoding="utf-8")

    # Observed.json in 5-min windows after 5-min warm-up [50700, 60900)
    obs_records: list[dict] = []
    n_bins = int((DEMAND_END_SEC - WARMUP_END_SEC) / 300.0)
    for b in range(n_bins):
        t0 = WARMUP_END_SEC + b * 300.0
        t1 = t0 + 300.0
        m_start = int((t0 - START_SEC) / 60.0)
        m_end = int((t1 - START_SEC) / 60.0)
        sub_idx = full_idx[m_start:m_end]
        for spec in link_specs:
            if spec.get("skip_obs"):
                continue
            q_ser, v_ser = site_totals(piv_q, piv_v, spec["site"], spec.get("lane_filter"))
            q_mean = float(q_ser.loc[sub_idx].mean())
            q_sub = q_ser.loc[sub_idx]
            v_sub = v_ser.loc[sub_idx]
            if q_sub.sum() > 0:
                v_mean = float((q_sub * v_sub).sum() / q_sub.sum())
            else:
                v_mean = float(v_sub.mean())
            obs_records.append({
                "link_id": spec["id"],
                "t_start": t0,
                "t_end": t1,
                "flow_veh_h": round(q_mean, 1),
                "speed_kmh": round(v_mean, 1),
                "label": spec["label"],
            })

    (OUT_DIR / "observed.json").write_text(json.dumps(obs_records, indent=1), encoding="utf-8")
    print(f"Built {OUT_DIR}: {len(NODES)} nodes, {len(link_specs)} links, {len(demand_rows)} demand rows, {len(active_ops)} gate ops, {len(obs_records)} observed windows")


if __name__ == "__main__":
    build()
