"""Build the runnable NDW A15 Papendrecht (km 76.4 -> 80.8 eastbound) pipe-stream scenario.

Reads the screened 1-minute per-lane dataset generated by ``prepare_dexter_export.py``
and produces ``scenarios/a15_papendrecht/``:
  - ``network.geojson`` (15 nodes, 14 links with multi-pipe lane groups & ``moves``)
  - ``config.json``
  - ``demand.json`` (1-minute resolution OD demand with exact integer vehicle counts)
  - ``patches/gate.json`` (downstream ramp throttling observed at N3 & Sliedrecht)
  - ``observed.json`` (5-minute station flow & speed checks across all 13 sensors)
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[2]
SCREENED_CSV = ROOT / "scenarios" / "ndw" / "data" / "screened" / "series_per_lane_minute.csv"
OUT_DIR = ROOT / "scenarios" / "a15_papendrecht"

# 14:00:00Z to 16:55:00Z (175 minutes = 35 x 5-min bins)
T_START_STR = "2026-11-26 14:00:00+00:00"
T_END_STR = "2026-11-26 16:54:00+00:00"  # inclusive last 1-min bin [16:54, 16:55)
START_SEC = 50400.0  # 14:00:00 UTC in seconds since midnight
DEMAND_END_SEC = 60900.0  # 16:55:00 UTC
SIM_DURATION = 11400.0  # 190 minutes -> tail drains cleanly by 61800.0
WARMUP_END_SEC = 50700.0  # skip first 5 min [50400, 50700) in observed.json


def haversine_m(p1: tuple[float, float], p2: tuple[float, float]) -> float:
    lon1, lat1 = map(math.radians, p1)
    lon2, lat2 = map(math.radians, p2)
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = math.sin(dlat / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2) ** 2
    return 2.0 * 6371000.0 * math.asin(math.sqrt(a))


